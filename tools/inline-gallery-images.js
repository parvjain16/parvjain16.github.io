#!/usr/bin/env node

/*
 * Build self-contained gallery textures for direct local-document viewing.
 * Originals in images/gallery are never modified; re-encoded copies live in
 * gallery-textures/encoded and the generated data map lives at the repo root.
 */
const fs = require("node:fs");
const path = require("node:path");
const { execFileSync } = require("node:child_process");

const repoRoot = path.resolve(__dirname, "..");
const sourceDir = path.join(repoRoot, "images", "gallery");
const outputDir = path.join(repoRoot, "gallery-textures", "encoded");
const outputFile = path.join(repoRoot, "gallery-textures.js");
const maxPayloadBytes = 25 * 1024 * 1024;
const names = fs.readdirSync(sourceDir)
    .filter((name) => /^gallery-\d{2}\.jpg$/i.test(name))
    .sort((left, right) => left.localeCompare(right, undefined, { numeric: true }));

fs.mkdirSync(outputDir, { recursive: true });

const encoded = [];
for (const name of names) {
    const input = path.join(sourceDir, name);
    const output = path.join(outputDir, name);
    if (!fs.existsSync(input)) {
        throw new Error(`Missing gallery image: ${input}`);
    }

    execFileSync("/usr/bin/sips", [
        "--resampleHeightWidthMax", "1024",
        "--setProperty", "format", "jpeg",
        "--setProperty", "formatOptions", "80",
        input,
        "--out", output
    ], { stdio: "ignore" });

    const bytes = fs.readFileSync(output);
    encoded.push({
        name,
        source: `images/gallery/${name}`,
        bytes,
        size: bytes.length
    });
}

const totalBytes = encoded.reduce((sum, item) => sum + item.size, 0);
for (const item of encoded) {
    console.log(`${item.source}: ${item.size.toLocaleString()} bytes`);
}
console.log(`TOTAL_PAYLOAD_BYTES: ${totalBytes.toLocaleString()}`);
console.log(`TOTAL_PAYLOAD_MB: ${(totalBytes / (1024 * 1024)).toFixed(2)}`);

if (totalBytes > maxPayloadBytes) {
    throw new Error(`Inline payload exceeds 25MB (${totalBytes} bytes); gallery-textures.js was not written.`);
}

const lines = [
    "/* Generated by tools/inline-gallery-images.js. Do not edit by hand. */",
    "window.GALLERY_TEXTURES = Object.freeze({"
];
encoded.forEach((item, index) => {
    const comma = index === encoded.length - 1 ? "" : ",";
    lines.push(
        `    ${JSON.stringify(item.source)}: ${JSON.stringify(`data:image/jpeg;base64,${item.bytes.toString("base64")}`)}${comma}`
    );
});
lines.push("});", "");
fs.writeFileSync(outputFile, lines.join("\n"));
console.log(`WROTE: ${outputFile}`);
